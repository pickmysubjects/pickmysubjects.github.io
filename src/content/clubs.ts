import type { Topic } from "@/engine/schema";

/**
 * Every UMSU club, as the UMSU clubs listing shows it (name, category, link), with the topics
 * students pick as interests where a club is tied to what they study or want to work in.
 *
 * Source: https://umsu.unimelb.edu.au/buddy-up/clubs/clubs-listing/ (246 clubs), checked
 * 2026-11-04. Clubs come and go each year: check the listing again every November.
 *
 * Only course, careers and arts clubs carry topics, so only they are suggested from a student's
 * interests; cultural, faith, political, food and games clubs are listed for students to browse.
 * Clubs for one gender or identity carry none either: we don't know the student's, and won't guess.
 */
export const CLUB_CATEGORIES = [
  "course",
  "special-interest",
  "culture",
  "sports-games",
  "music-dance",
  "reading-watching",
  "community",
  "political",
  "spiritual",
  "food",
] as const;
export type ClubCategory = (typeof CLUB_CATEGORIES)[number];

export interface Club {
  name: string;
  /** This site's address for it: /clubs/<slug>/. */
  slug: string;
  category: ClubCategory;
  /** The club's page on the UMSU site, where students join. */
  url: string;
  topics: Topic[];
  /** Degrees whose own student society it is. */
  courses?: string[];
}

const JOIN = "https://umsu.unimelb.edu.au/buddy-up/clubs/clubs-listing/join/";

export const CLUBS_LISTING =
  "https://umsu.unimelb.edu.au/buddy-up/clubs/clubs-listing/";
export const CLUBS_CHECKED = "2026-11-04";

const club = (
  name: string,
  slug: string,
  category: ClubCategory,
  join: string,
  topics: Topic[] = [],
  courses?: string[],
): Club => ({
  name,
  slug,
  category,
  url: `${JOIN}${join}/`,
  topics,
  ...(courses ? { courses } : {}),
});

